"""Convert the G1 get-up USD collision model to standalone MJCF (requires usd-core, numpy, scipy).

Use the g1_29dof_rev_1_0.usd from LeggedLab's dev/get_up source.
Only rigid bodies, joints and collision geometry enter the training model.
"""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np
from pxr import Usd, UsdGeom, UsdPhysics
from scipy.spatial import ConvexHull
from scipy.spatial.transform import Rotation


def numbers(array):
    return " ".join(f"{x:.9g}" for x in np.asarray(array).flatten())


def quat(value):
    return np.r_[value.GetReal(), np.asarray(value.GetImaginary())]


def convex_points(vertices, limit=64):
    """Keep vertices farthest outside a growing hull until reaching the vertex budget."""
    points = np.unique(vertices, axis=0)
    points = points[ConvexHull(points).vertices]
    if len(points) <= limit:
        return points
    ids = list(np.unique(np.r_[points.argmin(0), points.argmax(0)]))
    while len(ids) < limit:
        planes = ConvexHull(points[ids]).equations
        error = (points @ planes[:, :3].T + planes[:, 3]).max(axis=1)
        idx = int(error.argmax())
        if error[idx] < 1e-7:
            break
        ids.append(idx)
    return points[ids]


def convert(source, output):
    stage = Usd.Stage.Open(str(source.resolve()))
    if UsdGeom.GetStageMetersPerUnit(stage) != 1:
        raise ValueError("Expected meter-scale Unitree USD")
    model = ET.Element("mujoco", model="leggedlab_g1_getup")
    model.append(ET.Comment("Unitree G1 rev 1.0 from LeggedLab dev/get_up (f5f54fe), generated by tools/convert_leggedlab_g1.py."))
    ET.SubElement(model, "compiler", angle="degree")
    asset = ET.SubElement(model, "asset")
    world = ET.SubElement(model, "worldbody")
    bodies = {"pelvis": ET.SubElement(world, "body", name="pelvis", pos="0 0 0.8")}
    ET.SubElement(bodies["pelvis"], "freejoint", name="floating_base_joint")
    joints = [UsdPhysics.RevoluteJoint(p) for p in stage.Traverse() if p.IsA(UsdPhysics.RevoluteJoint)]
    while joints:
        unresolved = []
        for joint in joints:
            parent, name = (prop.GetTargets()[0].name for prop in (joint.GetBody0Rel(), joint.GetBody1Rel()))
            if parent not in bodies:
                unresolved.append(joint)
                continue
            q0, q1 = [Rotation.from_quat(quat(attr.Get()), scalar_first=True)
                      for attr in (joint.GetLocalRot0Attr(), joint.GetLocalRot1Attr())]
            if np.linalg.norm(joint.GetLocalPos1Attr().Get()) > 1e-7:
                raise ValueError(f"Joint {joint.GetPath()} is offset from its child link origin")
            axis = np.eye(3)["XYZ".index(joint.GetAxisAttr().Get())]
            body = bodies[name] = ET.SubElement(bodies[parent], "body", name=name,
                pos=numbers(joint.GetLocalPos0Attr().Get()), quat=numbers((q0*q1.inv()).as_quat(scalar_first=True)))
            ET.SubElement(body, "joint", name=joint.GetPrim().GetName(), axis=numbers(q1.apply(axis)),
                          range=numbers([joint.GetLowerLimitAttr().Get(), joint.GetUpperLimitAttr().Get()]))
        if len(unresolved) == len(joints):
            raise ValueError("The USD contains a disconnected articulation")
        joints = unresolved

    for prim in stage.Traverse():
        if prim.HasAPI(UsdPhysics.MassAPI) and prim.GetName() in bodies:
            m = UsdPhysics.MassAPI(prim)
            ET.SubElement(bodies[prim.GetName()], "inertial", pos=numbers(m.GetCenterOfMassAttr().Get()),
                          mass=numbers(m.GetMassAttr().Get()), diaginertia=numbers(m.GetDiagonalInertiaAttr().Get()),
                          quat=numbers(quat(m.GetPrincipalAxesAttr().Get())))

    cache = UsdGeom.XformCache()
    counts = {}
    for prim in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
        if not prim.HasAPI(UsdPhysics.CollisionAPI):
            continue
        part = prim
        while part and not part.HasAPI(UsdPhysics.RigidBodyAPI):
            part = part.GetParent()
        name = part.GetName()
        i = counts[name] = counts.get(name, 0) + 1
        feature = name.removesuffix("_link")
        if feature.endswith("_ankle_roll"):
            feature = feature.replace("_ankle_roll", f"_foot{i}")
        elif feature.endswith("_knee") and i == 2:
            feature = feature.replace("_knee", "_shin")
        elif i > 1:
            feature += f"_{i}"
        attributes = {"name": feature + "_collision", "type": prim.GetTypeName().lower()}
        local, _ = cache.ComputeRelativeTransform(prim, part)
        matrix = np.asarray(local)
        scale = np.linalg.norm(matrix[:3, :3], axis=1)
        if prim.IsA(UsdGeom.Mesh):
            if UsdPhysics.MeshCollisionAPI(prim).GetApproximationAttr().Get() != "convexHull":
                raise ValueError(f"Unsupported USD collision mesh approximation at {prim.GetPath()}")
            points = np.asarray(UsdGeom.Mesh(prim).GetPointsAttr().Get()) @ matrix[:3, :3] + matrix[3, :3]
            ET.SubElement(asset, "mesh", name=feature, vertex=numbers(convex_points(points)))
            attributes["mesh"] = feature
        else:
            attributes["pos"] = numbers(matrix[3, :3])
            attributes["quat"] = numbers(Rotation.from_matrix((matrix[:3, :3] / scale[:, None]).T).as_quat(scalar_first=True))
            if prim.IsA(UsdGeom.Cube):
                attributes.update(type="box", size=numbers(.5 * scale * UsdGeom.Cube(prim).GetSizeAttr().Get()))
            elif prim.IsA(UsdGeom.Sphere):
                np.testing.assert_allclose(scale, scale[0], rtol=1e-6)
                attributes["size"] = numbers(UsdGeom.Sphere(prim).GetRadiusAttr().Get() * scale[0])
            elif prim.IsA(UsdGeom.Cylinder):
                cylinder = UsdGeom.Cylinder(prim)
                assert cylinder.GetAxisAttr().Get() == "Z" and np.isclose(scale[0], scale[1])
                attributes["size"] = numbers([cylinder.GetRadiusAttr().Get()*scale[0], .5*cylinder.GetHeightAttr().Get()*scale[2]])
            else:
                raise ValueError(prim.GetPath())
        ET.SubElement(bodies[name], "geom", **attributes)
    for side in ("left", "right"):
        ET.SubElement(bodies[f"{side}_ankle_roll_link"], "site", name=f"{side}_foot", pos=".035 0 -.024", size=".001")
    ET.indent(model, space="  ")
    output.write_text(ET.tostring(model, encoding="unicode")+"\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("usd", type=Path)
    parser.add_argument("--out", type=Path, default=Path("assets/g1_leggedlab.xml"))
    args = parser.parse_args()
    convert(args.usd, args.out)
